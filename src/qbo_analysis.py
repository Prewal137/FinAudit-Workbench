"""QuickBooks Profit & Loss analysis utilities.

This module provides a lightweight adapter that consumes the JSON file produced by
`get_profit_and_loss` (the MCP tool) and calculates derived financial ratios.
It deliberately works with **aggregate** period totals – the QuickBooks API does
not return monthly breakdowns for the YTD request, so only overall figures are
available.

The primary public function is :func:`analyze_profit_and_loss` which returns a
dictionary of the original fields plus a few calculated percentages.
"""

import json
from pathlib import Path
from typing import Dict, Any, Optional


def _load_report(report_path: Path) -> Dict[str, Any]:
    """Read the JSON file generated by the MCP ``get_profit_and_loss`` tool.

    The function raises ``FileNotFoundError`` if the file does not exist and
    ``json.JSONDecodeError`` for malformed content – both are considered unrecoverable
    for the analysis workflow and will propagate to the caller.
    """
    with report_path.open("r", encoding="utf-8") as f:
        data = json.load(f)
    return data


def _safe_float(value: Any) -> Optional[float]:
    """Convert a QuickBooks numeric string to ``float`` safely.

    ``None`` or missing values return ``None`` so that downstream calculations can
    recognise the metric as unavailable.  Strings are cast to ``float``; any
    conversion error also yields ``None``.
    """
    if value is None:
        return None
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def _pct(numerator: Optional[float], denominator: Optional[float]) -> Optional[float]:
    """Calculate a percentage with two‑decimal rounding.

    Returns ``None`` when either operand is ``None`` or the denominator is zero.
    """
    if numerator is None or denominator is None or denominator == 0:
        return None
    return round((numerator / denominator) * 100, 2)


def analyze_profit_and_loss(report_path: Path) -> Dict[str, Any]:
    """Adapt a QuickBooks P&L JSON file to a richer analysis dict.

    The returned mapping includes:

    * ``period`` – the start and end dates from the original report.
    * ``currency`` – the currency code (e.g. "USD").
    * ``source`` – a copy of the raw ``report`` dict for traceability.
    * ``derived`` – calculated percentages:
        * ``gross_margin_pct``  = Gross Profit / Total Revenue * 100
        * ``operating_margin_pct`` = Net Operating Income / Total Revenue * 100
        * ``net_margin_pct`` = Net Income / Total Revenue * 100

    Percentages are rounded to two decimal places.  When the required numerator
    or denominator is missing, the entry is ``None`` and the accompanying
    ``metric_status`` entry will be ``unavailable``.
    """
    data = _load_report(report_path)

    period = data.get("period", {})
    currency = data.get("currency")
    raw_report = data.get("report", {})
    metric_status = data.get("metric_status", {})

    # Normalize metric_status entries: replace None with "unavailable" for consistency
    for key, val in list(metric_status.items()):
        if val is None:
            metric_status[key] = "unavailable"


    # Extract numbers using the safe helper.
    total_rev = _safe_float(raw_report.get("total_revenue"))
    gross_profit = _safe_float(raw_report.get("gross_profit"))
    net_operating_income = _safe_float(raw_report.get("net_operating_income"))
    net_income = _safe_float(raw_report.get("net_income"))

    derived = {
        "gross_margin_pct": _pct(gross_profit, total_rev),
        "operating_margin_pct": _pct(net_operating_income, total_rev),
        "net_margin_pct": _pct(net_income, total_rev),
    }

    return {
        "period": period,
        "currency": currency,
        "source": raw_report,
        "derived": derived,
        "metric_status": metric_status,
    }

__all__ = ["analyze_profit_and_loss"]
