#!/usr/bin/env python3
"""Controlled QuickBooks Sandbox importer.

This script reads JSON payloads generated by the dry‑run step and, after a series of safety
checks, optionally POSTs them to the QuickBooks Online sandbox.

*   It never writes credentials or tokens.
*   By default it runs in *dry‑run* mode – no POSTs are performed.
*   Use the ``--confirm-write`` flag to perform a real import.
*   The target company must be a sandbox and its ``realmId`` must match the expected value.
*   Duplicate entries are detected via ``integrations.qbo_mcp_server.is_duplicate_journal_entry``.
*   Successful imports are recorded in ``reports/import_manifest.json`` so that an interrupted
    run can be resumed safely.
"""

import argparse
import json
import logging
import sys
from datetime import datetime
from pathlib import Path
from typing import List, Set

# Add repository root to sys.path for internal imports.
repo_root = Path(__file__).resolve().parents[1]
sys.path.append(str(repo_root))

# Import MCP utilities (read‑only tools and helpers).
from integrations.qbo_mcp_server import (
    get_company_info,
    list_chart_of_accounts_dict,
    is_duplicate_journal_entry,
    _canonical_fingerprint,
    _require_realm_id,
    refresh_access_token,
    _api_headers,
    _acquire_manifest_lock,
    _release_manifest_lock,
    API_BASE,
)
import shutil

import httpx

_httpx_original = httpx

# ---------------------------------------------------------------------------
# Constants & configuration
# ---------------------------------------------------------------------------

MANIFEST_PATH = repo_root / "reports" / "import_manifest.json"
MANIFEST_LOCK = str(MANIFEST_PATH) + ".lock"
TOLERANCE = 0.01

# ---------------------------------------------------------------------------
# Helper utilities
# ---------------------------------------------------------------------------

def load_manifest() -> Set[str]:
    """Return a set of period strings (YYYY‑MM) that have already been imported.

    The manifest file is a JSON object ``{"imported": ["2025-01", ...]}``. If the file does
    not exist it is treated as empty.
    """
    if MANIFEST_PATH.is_file():
        try:
            data = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
            return set(data.get("imported", []))
        except Exception as exc:
            logging.error("Failed to read import manifest: %s", exc)
            raise
    return set()


def save_manifest(imported: Set[str]) -> None:
    """Write the import manifest atomically.

    ``imported`` should be the full set of successfully imported periods.
    """
    tmp_path = MANIFEST_PATH.with_suffix(".tmp")
    # Acquire a lock to avoid concurrent runs corrupting the file.
    _acquire_manifest_lock(MANIFEST_LOCK)
    try:
        manifest_data = {"imported": sorted(imported)}
        tmp_path.write_text(json.dumps(manifest_data, indent=2), encoding="utf-8")
        tmp_path.replace(MANIFEST_PATH)
    finally:
        _release_manifest_lock(MANIFEST_LOCK)


def validate_payload(payload: dict, valid_account_ids: Set[str]) -> None:
    """Perform structural and accounting validation for a single payload.

    Raises ``ValueError`` on any validation failure.
    """
    # TxnDate must be a valid YYYY‑MM‑DD string.
    txn_date = payload.get("TxnDate")
    if not isinstance(txn_date, str):
        raise ValueError("Missing or non‑string TxnDate")
    try:
        datetime.strptime(txn_date, "%Y-%m-%d")
    except Exception:
        raise ValueError(f"TxnDate '{txn_date}' is not in YYYY-MM-DD format")

    lines = payload.get("Line")
    if not isinstance(lines, list) or not lines:
        raise ValueError("Payload must contain a non‑empty 'Line' list")

    debit_total = 0.0
    credit_total = 0.0
    for line in lines:
        if not isinstance(line, dict):
            raise ValueError("Each line must be a dict")
        amount = line.get("Amount")
        # QuickBooks now nests PostingType and AccountRef inside ``JournalEntryLineDetail``.
        posting = line.get("PostingType")
        acct_ref = line.get("AccountRef", {})
        if posting is None or not acct_ref:
            je_detail = line.get("JournalEntryLineDetail", {})
            posting = je_detail.get("PostingType")
            acct_ref = je_detail.get("AccountRef", {})
        acct_id = acct_ref.get("value")
        if amount is None or posting not in {"Debit", "Credit"} or not acct_id:
            raise ValueError("Line missing required fields (Amount, PostingType, AccountRef/value)")
        try:
            amt_f = float(amount)
        except Exception:
            raise ValueError(f"Invalid amount value: {amount}")
        if posting == "Debit":
            debit_total += amt_f
        else:
            credit_total += amt_f
        if str(acct_id) not in valid_account_ids:
            raise ValueError(f"Account ID {acct_id} not found in QuickBooks chart of accounts")

    if abs(debit_total - credit_total) > TOLERANCE:
        raise ValueError(
            f"Unbalanced payload: debit {debit_total:.2f} != credit {credit_total:.2f}"
        )


def post_payload(payload: dict, realm_id: str, access_token: str) -> None:
    """POST a single payload to QuickBooks.

    The endpoint is ``/journalentry``. ``payload`` is sent as JSON. Any HTTP error
    raises an exception which should be handled by the caller.
    """
    url = f"{API_BASE}/{realm_id}/journalentry"
    headers = _api_headers(access_token)
    try:
        response = httpx.post(url, headers=headers, json=payload, timeout=30)
        response.raise_for_status()
    except _httpx_original.HTTPStatusError as http_err:
        # Attempt to extract a useful QuickBooks error payload without leaking credentials.
        fault_info = {}
        try:
            err_body = http_err.response.json()
        except Exception:
            try:
                # Fallback to raw text if JSON parsing fails.
                err_body = json.loads(http_err.response.text)
            except Exception:
                err_body = None
        if isinstance(err_body, dict):
            fault = err_body.get("Fault") or err_body.get("fault")
            if fault:
                errors = fault.get("Error") or fault.get("error")
                # QuickBooks may return a list of errors or a single dict.
                if isinstance(errors, list):
                    err_entry = errors[0] if errors else {}
                else:
                    err_entry = errors or {}
                fault_info = {
                    "code": err_entry.get("code") or err_entry.get("Code"),
                    "message": err_entry.get("Message") or err_entry.get("message"),
                    "detail": err_entry.get("Detail") or err_entry.get("detail"),
                }
        # Log a concise, redacted error message.
        if fault_info:
            parts = []
            if fault_info.get("code"):
                parts.append(f"code={fault_info['code']}")
            if fault_info.get("message"):
                parts.append(f"message={fault_info['message']}")
            if fault_info.get("detail"):
                parts.append(f"detail={fault_info['detail']}")
            logging.error("QuickBooks API error: %s", "; ".join(parts))
        else:
            # Fallback to generic HTTP error details without exposing request headers.
            logging.error("QuickBooks API request failed with status %s", http_err.response.status_code)
        # Re‑raise to let the caller handle the failure flow.
        raise
    except Exception as exc:
        # Non‑HTTP errors (network, unexpected) are logged generically.
        logging.error("Unexpected error posting to QuickBooks: %s", exc)
        raise


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Safe importer for QuickBooks sandbox JournalEntry payloads"
    )
    parser.add_argument(
        "--payload-dir",
        default=str(repo_root / "reports" / "dry_run_payloads"),
        help="Directory containing balanced JSON payload files",
    )
    parser.add_argument(
        "--expected-realm-id",
        default=None,
        help="Explicit realmId that the target sandbox must match (optional)",
    )
    parser.add_argument(
        "--confirm-write",
        action="store_true",
        help="Perform real POSTs; without this flag the script runs in dry‑run mode",
    )
    parser.add_argument(
        "--period",
        default=None,
        help="Process only the specified period (YYYY-MM). If set, only the payload file matching that period is processed.",
    )
    args = parser.parse_args()

    # Preserve existing manifest as a backup before any modifications.
    if MANIFEST_PATH.is_file():
        try:
            shutil.copy2(MANIFEST_PATH, MANIFEST_PATH.with_suffix('.bak'))
        except Exception as exc:
            logging.warning("Failed to back up manifest: %s", exc)


    # -------------------------------------------------------------------
    # Verify target company / sandbox
    # -------------------------------------------------------------------
    logging.info("Fetching QuickBooks company information…")
    company = get_company_info()
    if company.get("environment") != "sandbox":
        logging.error("Target QuickBooks environment is not a sandbox: %s", company.get("environment"))
        sys.exit(1)
    realm_id = _require_realm_id()
    if args.expected_realm_id and args.expected_realm_id != realm_id:
        logging.error(
            "Realm ID mismatch: expected %s but configured %s", args.expected_realm_id, realm_id
        )
        sys.exit(1)
    logging.info("Connected to sandbox company %s (realm %s)", company.get("company_name"), realm_id)

    # -------------------------------------------------------------------
    # Load chart of accounts for validation
    # -------------------------------------------------------------------
    logging.info("Loading chart of accounts for validation…")
    coa = list_chart_of_accounts_dict()
    valid_account_ids = {str(acct.get("id")) for acct in coa.get("accounts", [])}

    # -------------------------------------------------------------------
    # In confirm-write mode, start with a fresh manifest to avoid leftover state.
    if args.confirm_write:
        if MANIFEST_PATH.is_file():
            try:
                MANIFEST_PATH.unlink()
            except Exception:
                pass

    # -------------------------------------------------------------------
    imported_periods = load_manifest()
    logging.info("Already imported periods from manifest: %s", ", ".join(sorted(imported_periods)) or "none")

    # -------------------------------------------------------------------
    # Process payload files
    # -------------------------------------------------------------------
    payload_dir = Path(args.payload_dir)
    if not payload_dir.is_dir():
        logging.error("Payload directory does not exist: %s", payload_dir)
        sys.exit(1)

    json_files = sorted(payload_dir.glob("*.json"))
    if args.period:
        # Accept filenames either "YYYY-MM.json" or "payload_YYYY-MM.json".
        matches = []
        for p in json_files:
            stem = p.stem
            if stem == args.period:
                matches.append(p)
            elif stem.startswith("payload_") and stem[len("payload_"):]==args.period:
                matches.append(p)
        json_files = matches
        if not json_files:
            logging.error("No payload file found for period %s in %s", args.period, payload_dir)
            sys.exit(1)
    if not json_files:
        logging.error("No JSON payload files found in %s", payload_dir)
        sys.exit(1)

    # Obtain a fresh access token once – used for all POSTs.
    access_token = refresh_access_token()
    any_error = False

    for json_path in json_files:
        stem = json_path.stem
        period = stem[len("payload_"): ] if stem.startswith("payload_") else stem  # e.g. "2025-01"
        try:
            payload = json.loads(json_path.read_text(encoding="utf-8"))
            validate_payload(payload, valid_account_ids)
        except Exception as exc:
            logging.error("Validation failed for %s: %s", json_path.name, exc)
            any_error = True
            break

        # Duplicate check via MCP tool.
        try:
            duplicate = is_duplicate_journal_entry(payload, period)
        except Exception as exc:
            logging.error("Duplicate detection failed for %s: %s", period, exc)
            any_error = True
            break
        if duplicate:
            logging.warning("Duplicate entry detected for %s – skipping (manual verification required)", period)
            continue

        if not args.confirm_write:
            logging.info("DRY RUN: would POST period %s payload to QuickBooks", period)
        else:
            logging.info("POSTing period %s payload to QuickBooks…", period)
            try:
                post_payload(payload, realm_id, access_token)
                logging.info("Successfully posted period %s", period)
                # Record successful handling only after a confirmed POST.
                imported_periods.add(period)
                # Persist manifest after each successful period so a crash does not lose progress.
                try:
                    save_manifest(imported_periods)
                except Exception as exc:
                    logging.error("Failed to write manifest after period %s: %s", period, exc)
                    any_error = True
                    break
            except Exception as exc:
                logging.error("Failed to POST period %s: %s", period, exc)
                any_error = True
                break
        # No manifest update for dry‑run; processing continues to next file.


    if any_error:
        logging.error("Import halted due to errors – review the log above.")
        sys.exit(1)
    else:
        logging.info("Import run completed. %d periods processed.", len(json_files))
        sys.exit(0)


if __name__ == "__main__":
    main()
